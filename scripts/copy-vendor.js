// Runs automatically via "postinstall" once marked and pdfjs-dist are in
// node_modules. The renderer has no bundler and no nodeIntegration, so it
// can't `require()` these packages directly — instead we copy their
// prebuilt browser bundles into src/renderer/vendor/ and load them as
// plain <script> tags / ES modules (see index.html and pdfViewer.js).
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const vendorDir = path.join(root, 'src', 'renderer', 'vendor');
fs.mkdirSync(vendorDir, { recursive: true });

const pairs = [
  { from: ['node_modules', 'marked', 'lib', 'marked.umd.js'], to: ['marked.min.js'] },
  { from: ['node_modules', 'pdfjs-dist', 'build', 'pdf.mjs'], to: ['pdf.mjs'] },
  { from: ['node_modules', 'pdfjs-dist', 'build', 'pdf.worker.mjs'], to: ['pdf.worker.mjs'] },
  { from: ['node_modules', 'pdfjs-dist', 'web', 'pdf_viewer.mjs'], to: ['pdf_viewer.mjs'] },
  { from: ['node_modules', 'pdfjs-dist', 'web', 'pdf_viewer.css'], to: ['pdf_viewer.css'] },
];

let missing = [];
for (const { from, to } of pairs) {
  const src = path.join(root, ...from);
  const dest = path.join(vendorDir, ...to);
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, dest);
    console.log(`[copy-vendor] copied ${from.join('/')}`);
  } else {
    missing.push(from.join('/'));
  }
}

if (missing.length) {
  console.warn('[copy-vendor] Missing (Markdown rendering / the in-app PDF viewer will be unavailable until these exist):');
  missing.forEach((m) => console.warn('  - ' + m));
  console.warn('[copy-vendor] Try `npm install` again — marked/pdfjs-dist may not have installed correctly.');
} else {
  console.log('[copy-vendor] Renderer vendor assets ready.');
}

// Emoji fallback for the UI's icons (see the font-family note in styles.css):
// an "AppEmoji" alias that prefers the OS's own emoji font and falls back to
// a bundled Noto Emoji (OFL-1.1, ~0.5 MB), restricted to emoji code points.
{
  const pkg = path.join(root, 'node_modules', '@fontsource', 'noto-emoji');
  const file = 'noto-emoji-emoji-400-normal.woff2';
  const dest = path.join(vendorDir, 'emoji');
  if (fs.existsSync(path.join(pkg, 'files', file))) {
    fs.mkdirSync(dest, { recursive: true });
    fs.copyFileSync(path.join(pkg, 'files', file), path.join(dest, file));
    fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(dest, 'LICENSE-OFL.txt'));
    fs.writeFileSync(path.join(dest, 'emoji.css'), [
      '/* Generated by scripts/copy-vendor.js — do not edit. */',
      '@font-face {',
      "  font-family: 'AppEmoji';",
      "  src: local('Segoe UI Emoji'), local('Apple Color Emoji'), local('Noto Color Emoji'),",
      `    url(./${file}) format('woff2');`,
      '  unicode-range: U+2600, U+26A0, U+23E9-23FA, U+25B6, U+FE0F, U+200D, U+1F000-1FAFF;',
      '  font-display: swap;',
      '}',
      '',
    ].join('\n'));
    console.log('[copy-vendor] prepared emoji fallback font (vendor/emoji)');
  } else {
    console.warn('[copy-vendor] Missing @fontsource/noto-emoji — icons will show as boxes on systems without an emoji font.');
  }
}
